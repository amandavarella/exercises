// Creates week-<number>/index.html for every week in weeks.js, from tools/week-page.html.
//   node tools/sync-weeks.js          write the week pages
//   node tools/sync-weeks.js --check  fail if any week page is missing or out of date (used in CI)
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const ctx = { localStorage: undefined };
vm.runInNewContext(fs.readFileSync(path.join(root, "weeks.js"), "utf8") + ";this.WEEKS = WEEKS; this.weekSlug = weekSlug;", ctx);

const template = fs.readFileSync(path.join(__dirname, "week-page.html"), "utf8").replace(
  /<!-- Template for every.*?-->/,
  "<!-- Generated by tools/sync-weeks.js from tools/week-page.html. Edit the template, not this file. -->"
);
const check = process.argv.includes("--check");
const problems = [];

const numbers = ctx.WEEKS.map((w) => w.number);
const dupes = numbers.filter((n, i) => numbers.indexOf(n) !== i);
if (dupes.length) problems.push(`Duplicate week numbers in weeks.js: ${dupes.join(", ")}`);

for (const week of ctx.WEEKS) {
  if (!Number.isInteger(week.number) || week.number < 1) {
    problems.push(`Week number must be a positive whole number: ${JSON.stringify(week.number)}`);
    continue;
  }
  const file = path.join(root, ctx.weekSlug(week), "index.html");
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (current === template) continue;
  if (check) {
    problems.push(`${path.relative(root, file)} is ${current === null ? "missing" : "out of date"}`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, template);
    console.log(`Wrote ${path.relative(root, file)}`);
  }
}

// Week folders with no matching week in weeks.js
const slugs = new Set(ctx.WEEKS.map(ctx.weekSlug));
for (const dir of fs.readdirSync(root)) {
  if (/^week-\d+$/.test(dir) && !slugs.has(dir)) problems.push(`${dir}/ has no matching week in weeks.js`);
}

if (problems.length) {
  console.error(problems.join("\n"));
  if (check) console.error('Run "node tools/sync-weeks.js" and commit the result.');
  process.exit(1);
}
console.log(`All ${ctx.WEEKS.length} week page(s) are in place.`);
